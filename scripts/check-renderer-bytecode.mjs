#!/usr/bin/env node

// Adapted from pwrdrvr/PwrAgent#3756, using PwrGit's Vite 7/esbuild pipeline.
import { spawn } from "node:child_process";
import { once } from "node:events";
import { writeSync } from "node:fs";
import { readdir, writeFile } from "node:fs/promises";
import { createRequire } from "node:module";
import { dirname, relative, resolve } from "node:path";
import { createInterface } from "node:readline";
import { fileURLToPath } from "node:url";
import { setFlagsFromString } from "node:v8";
import * as vm from "node:vm";
import { isCliEntrypoint } from "./lib/cli-entrypoint.mjs";

const scriptPath = fileURLToPath(import.meta.url);
const repoRoot = resolve(dirname(scriptPath), "..");
const desktopRoot = resolve(repoRoot, "apps/desktop");
// Ratchet near the current ~26 KiB maximum, below the old slow controller.
export const BYTECODE_BUDGET = 28 * 1024;

export async function discoverModules(root) {
  const files = [];
  for (const entry of await readdir(root, { withFileTypes: true })) {
    const path = resolve(root, entry.name);
    if (entry.isDirectory() && !["test-support", "__tests__", "node_modules"].includes(entry.name)) {
      files.push(...await discoverModules(path));
    } else if (entry.isFile() && /\.[cm]?[jt]sx?$/.test(entry.name)
      && !/\.(?:test|spec|d)\.[cm]?[jt]sx?$/.test(entry.name)) files.push(path);
  }
  return files.sort();
}

// Keep the argument/context layout of Vitest 4's module-evaluator.js.
export function wrapVitestModule(code) {
  const args = [
    "__vite_ssr_exports__", "__vite_ssr_import_meta__", "__vite_ssr_import__",
    "__vite_ssr_dynamic_import__", "__vite_ssr_exportAll__", "__vite_ssr_exportName__",
    "__filename", "__dirname", "module", "exports", "require",
  ];
  return `'use strict';async (${args.join(",")})=>{{${code}\n}}`;
}

async function compileModules() {
  for await (const line of createInterface({ input: process.stdin })) {
    const { file, variant, code, esm } = JSON.parse(line);
    writeSync(1, `@@FILE ${JSON.stringify({ file, variant })}\n`);
    setFlagsFromString("--print-bytecode --print-bytecode-filter=*");
    try {
      // Parse/compile only. Never link, evaluate, or execute application imports.
      // Identical client/SSR output must not hit V8's compilation cache and
      // silently omit a variant from --print-bytecode.
      const uniqueCode = `${code}\n// bytecode ${JSON.stringify({ file, variant })}`;
      if (esm) new vm.SourceTextModule(uniqueCode, { identifier: file });
      else new vm.Script(uniqueCode, { filename: file });
    } finally {
      setFlagsFromString("--no-print-bytecode");
    }
  }
}

export async function measureBytecode(modules) {
  const child = spawn(process.execPath, ["--no-lazy", "--experimental-vm-modules", scriptPath, "--compile"], {
    cwd: repoRoot, stdio: ["pipe", "pipe", "pipe"],
    // NODE_OPTIONS must not silently override the compilation oracle's tiers.
    env: { ...process.env, NODE_OPTIONS: "" },
  });
  const finished = once(child, "close");
  let diagnostics = "";
  child.stderr.on("data", (chunk) => { diagnostics = (diagnostics + chunk).slice(-4000); });
  const records = [];
  const counts = new Map();
  let file, variant, name, ordinal;
  const output = createInterface({ input: child.stdout });
  output.on("line", (line) => {
    if (line.startsWith("@@FILE ")) {
      ({ file, variant } = JSON.parse(line.slice(7)));
      ordinal = 0;
      counts.set(`${file}:${variant}`, 0);
    } else if (line.startsWith("[generated bytecode for function: ")) {
      name = /^\[generated bytecode for function: (.*?) \(0x/.exec(line)?.[1];
    } else if (file && line.startsWith("Bytecode length: ")) {
      records.push({ file, variant, name: name || "(anonymous)", ordinal: ++ordinal, bytes: Number(line.slice(17)) });
      counts.set(`${file}:${variant}`, ordinal);
    }
  });
  // Reduce the disassembly as it streams; memory/log size is independent of it.
  try {
    for await (const module of modules) {
      if (!child.stdin.write(JSON.stringify(module) + "\n")) await once(child.stdin, "drain");
    }
    child.stdin.end();
    const [exitCode] = await finished;
    if (exitCode !== 0) throw new Error(`Bytecode compiler exited ${exitCode}: ${diagnostics}`);
    if (!counts.size || [...counts.values()].some((count) => count === 0)) {
      throw new Error(`V8 did not report bytecode for every module/variant: ${[...counts].filter(([, count]) => count === 0).map(([key]) => key).join(", ")}`);
    }
    return records;
  } finally {
    if (child.exitCode === null) child.kill();
  }
}

export function budgetFailures(records) {
  return records.filter(({ bytes }) => !Number.isInteger(bytes) || bytes < 0 || bytes > BYTECODE_BUDGET);
}

export function enforceBudget(records, report = console.error) {
  const failures = budgetFailures(records);
  for (const record of failures) report(`OVER BUDGET ${record.file}: ${record.name} #${record.ordinal} (${record.variant}): ${record.bytes} bytes > limit ${BYTECODE_BUDGET}`);
  if (failures.length) throw new Error(`${failures.length} renderer functions exceed the ${BYTECODE_BUDGET}-byte limit`);
}

export async function* transformedModules(sourceRoot, { productionInput } = {}) {
  const { createVitest } = await import("vitest/node");
  const desktopRequire = createRequire(resolve(desktopRoot, "package.json"));
  const { createServer, build, fetchModule, normalizePath } = await import(desktopRequire.resolve("vite"));
  const { resolveConfig } = await import(desktopRequire.resolve("electron-vite"));
  const files = await discoverModules(sourceRoot);
  if (!files.length) throw new Error(`No renderer modules discovered in ${sourceRoot}`);
  const context = await createVitest("test", { root: repoRoot, config: resolve(repoRoot, "vitest.config.ts"), watch: false }, { server: { hmr: false, ws: false, watch: null } });
  const previousNodeEnv = process.env.NODE_ENV;
  let devServer;
  try {
    await context.standalone();
    const environments = context.projects[0]?.vite.environments;
    if (!environments?.ssr || !environments.client) throw new Error("Vitest's transform environments are missing");
    const devConfig = await resolveConfig({ root: desktopRoot }, "serve");
    // Keep Fast Refresh's hook instrumentation; disable only its transport.
    devServer = await createServer({ ...devConfig.config.renderer, root: resolve(desktopRoot, "src/renderer"), configFile: false, server: { middlewareMode: true, watch: null, hmr: true, ws: false }, logLevel: "error" });
    for (const path of files) {
      const file = relative(repoRoot, path).replaceAll("\\", "/");
      for (const [name, environment] of [["Vitest-SSR", environments.ssr], ["Vitest-jsdom", environments.client]]) {
        const result = await fetchModule(environment, normalizePath(path), undefined, { inlineSourceMap: false });
        if (!("code" in result)) throw new Error(`No ${name} transform for ${file}`);
        yield { file, variant: name, code: wrapVitestModule(result.code) };
      }
      const dev = await devServer.transformRequest(`/@fs/${normalizePath(path)}`);
      if (!dev) throw new Error(`No development transform for ${file}`);
      yield { file, variant: "development", code: dev.code, esm: true };
    }
    const productionConfig = await resolveConfig({ root: desktopRoot }, "build", "production");
    const renderer = productionConfig.config.renderer;
    const built = await build({ ...renderer, root: resolve(desktopRoot, "src/renderer"), configFile: false, logLevel: "error", build: {
      ...renderer.build, write: false,
      ...(productionInput ? { rollupOptions: { ...renderer.build.rollupOptions, input: productionInput } } : {}),
    } });
    for (const bundle of [built].flat()) {
      for (const output of bundle.output) {
        if (output.type === "chunk") yield { file: `production/${output.fileName}`, variant: "production", code: output.code, esm: true };
        else if (/\.[cm]?js$/.test(output.fileName)) yield { file: `production/${output.fileName}`, variant: "production", code: typeof output.source === "string" ? output.source : Buffer.from(output.source).toString("utf8"), esm: true };
      }
    }
  } finally {
    await devServer?.close();
    await context.close();
    if (previousNodeEnv === undefined) delete process.env.NODE_ENV;
    else process.env.NODE_ENV = previousNodeEnv;
  }
}

export async function runCli(args = process.argv.slice(2)) {
  if (args[0] === "--compile") return compileModules();
  if (args.length && !(args.length === 2 && args[0] === "--json" && args[1])) throw new Error("Usage: check-renderer-bytecode.mjs [--json output.json]");
  const records = await measureBytecode(transformedModules(resolve(repoRoot, "apps/desktop/src/renderer/src")));
  if (args[0] === "--json" && args[1]) await writeFile(args[1], JSON.stringify(records, null, 2) + "\n");
  for (const record of [...records].sort((a, b) => b.bytes - a.bytes).slice(0, 12)) {
    console.log(`${record.file}: ${record.name} #${record.ordinal} (${record.variant}): ${record.bytes} bytes; limit ${BYTECODE_BUDGET}`);
  }
  enforceBudget(records);
  console.log(`Renderer bytecode passed: ${records.length} functions, ${new Set(records.map((r) => `${r.file}:${r.variant}`)).size} module/variants; Node ${process.version}, V8 ${process.versions.v8}`);
}

if (isCliEntrypoint(import.meta.url)) {
  runCli().catch((error) => { console.error(error); process.exitCode = 1; });
}
